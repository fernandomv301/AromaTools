# -*- coding: utf-8 -*-

def iter_atoms(ase_atoms):
    for sym, (x, y, z) in zip(ase_atoms.get_chemical_symbols(), ase_atoms.get_positions()):
        yield sym, float(x), float(y), float(z)

def chunks(seq, n):
    for i in range(0, len(seq), n):
        yield seq[i:i+n]

# ---------------- Gaussian ----------------

def write_g16(fname, ase_atoms, bq_pts, cfg):
    mem = cfg.get("memory", 16)
    procs = cfg.get("procs", 1)
    kline = cfg.get("keyword_line", "CAM-B3LYP DEF2TZVP").strip()
    charge = cfg.get("charge", 0)
    mult = cfg.get("multiplicity", 1)

    with open(fname, "w", encoding="utf-8") as f:
        if procs > 1:
            f.write(f"%NProcShared={procs}\n")
        f.write(f"%MEM={mem}GB\n")
        f.write(f"# {kline}\n\n")
        f.write("Generated by aromagnetic\n\n")
        f.write(f"{charge} {mult}\n")

        for sym, x, y, z in iter_atoms(ase_atoms):
            f.write(f"{sym:<2s} {x:14.8f} {y:14.8f} {z:14.8f}\n")
        for bq in bq_pts:
            x, y, z = bq[-3], bq[-2], bq[-1]
            f.write(f"Bq  {x:14.8f} {y:14.8f} {z:14.8f}\n")
        f.write("\n")

# ---------------- ORCA ----------------

def write_orca(fname, ase_atoms, bq_pts, cfg):
    kline  = cfg.get("keyword_line", "CAM-B3LYP def2-TZVP").strip()
    charge = cfg.get("charge", 0)
    mult   = cfg.get("multiplicity", 1)
    user   = cfg.get("orca_block")
    memory = cfg.get("memory", 16)
    procs  = int(cfg.get("procs", 1))
    maxcore_mb = int(float(memory) * 1000)

    with open(fname, "w", encoding="utf-8") as f:
        if kline:
            if not kline.startswith("!"):
                kline = "! " + kline
            f.write(kline + "\n")

        f.write(f"%maxcore {maxcore_mb}\n")
        if procs > 1:
            f.write(f"%pal\n  nprocs {procs}\nend\n")

        if user:
            f.write(user.rstrip() + "\n\n")

        f.write(f"* xyz {charge} {mult}\n")
        for sym, x, y, z in iter_atoms(ase_atoms):
            f.write(f"  {sym:<2s} {x:14.8f} {y:14.8f} {z:14.8f}\n")
        for bq in bq_pts:
            x, y, z = bq[-3], bq[-2], bq[-1]
            f.write(f"  H: {x:14.8f} {y:14.8f} {z:14.8f}\n")
        f.write("*\n")

# ---------------- Driver ----------------

def make_inputs(stub, ase_atoms, pts, cfg):
    da_max = max(5, int(cfg.get("da_max", 30)))
    program = (cfg.get("program") or "").strip().lower()
    name = cfg.get("name_molecule") or stub

    n = int(len(pts))
    if n == 0:
        return 0

    count = 0
    for k, block in enumerate(chunks(pts, da_max)):
        # Single chunk → no numeric suffix for cleaner filenames
        if n <= da_max and k == 0:
            fname = f"{name}.inp"
        else:
            fname = f"{name}_{k:04d}.inp"

        if "gaussian" in program:
            write_g16(fname, ase_atoms, block, cfg)
        else:
            write_orca(fname, ase_atoms, block, cfg)
        count += 1
    return count

def _parse_memory_gb(val, default=16):
    if val is None:
        return default
    s = str(val).strip().upper().replace("GB", "").replace("G", "").strip()
    try:
        return int(float(s))
    except ValueError:
        return default


def flatten_cfg(cfg_struct, section="GRID"):
    general = cfg_struct.get("general", {})
    block = cfg_struct.get(section, {})

    mem_raw   = general.get("MEMORY_GB") or general.get("MEMORY")
    procs_raw = general.get("PROCS") or general.get("NPROC") or general.get("NPROCS")

    flat = {
        "name_molecule": general.get("NAME_MOLECULE"),
        "program": general.get("PROGRAM"),
        "keyword_line": general.get("KEYWORD_LINE"),
        "procs": int(procs_raw) if procs_raw is not None else 4,
        "memory": _parse_memory_gb(mem_raw, default=16),
        "charge": int(general.get("CHARGE", 0) or 0),
        "multiplicity": int(general.get("MULTIPLICITY", 1) or 1),
        "orca_block": (cfg_struct.get("ORCA_BLOCK", {}).get("raw")
                       if isinstance(cfg_struct.get("ORCA_BLOCK"), dict) else None),
    }

    if section == "GRID":
        flat["da_max"] = int(block.get("GA_MAX", 30) or 30)
    elif section in ("VP", "PROFILE"):
        # da_max is overridden per-ring in get_profile anyway
        flat["da_max"] = int(block.get("NUM_GA", 1000) or 1000)

    return flat
